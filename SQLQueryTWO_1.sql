CREATE DATABASE QLSV
GO
USE QLSV
GO

CREATE TABLE CT_DAO_TAO(
	MA_CTDT VARCHAR(50) PRIMARY KEY,
	TEN_CTDT VARCHAR(50)
)
GO

CREATE TABLE KHOA_HOC(
	MA_KH VARCHAR(50) PRIMARY KEY,
	MA_CTDT VARCHAR(50) NOT NULL REFERENCES CT_DAO_TAO(MA_CTDT),
	TEN_KH NVARCHAR(50)
)
GO

CREATE TABLE LOP(
	MA_LOP VARCHAR(50) PRIMARY KEY,
	MA_KH VARCHAR(50) NOT NULL REFERENCES KHOA_HOC(MA_KH),
	TEN_LOP VARCHAR(50)
)
GO

CREATE TABLE MON_HOC(
	MA_MH VARCHAR(50) PRIMARY KEY,
	TEN_MH NVARCHAR(50),
	SO_TC INT
)
GO

CREATE TABLE SINH_VIEN(
	MA_SV VARCHAR(50) PRIMARY KEY,
	HO_TEN NVARCHAR(50),
	GIOI_TINH VARCHAR(50),
	NGAYSINH DATE,
	NOI_SINH NVARCHAR(50),
	MA_LOP VARCHAR(50) NOT NULL REFERENCES LOP(MA_LOP)
)
GO

CREATE TABLE KETQUATHI(
	DIEMTHI DECIMAL(4,2),
	MA_SV VARCHAR(50) NOT NULL REFERENCES SINH_VIEN(MA_SV),
	MA_MH VARCHAR(50) NOT NULL REFERENCES MON_HOC(MA_MH),
	LANTHI INT NOT NULL,
	PRIMARY KEY(MA_SV, MA_MH, LANTHI)
)
GO


