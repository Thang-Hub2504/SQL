USE QL_DIEM;
GO

IF OBJECT_ID('KETQUA', 'U')  IS NOT NULL DROP TABLE KETQUA;
IF OBJECT_ID('MON', 'U')     IS NOT NULL DROP TABLE MON;
IF OBJECT_ID('HOCVIEN', 'U') IS NOT NULL DROP TABLE HOCVIEN;
IF OBJECT_ID('LOP', 'U')     IS NOT NULL DROP TABLE LOP;
GO

CREATE TABLE LOP (
    MaLop  VARCHAR(50) PRIMARY KEY,
    TenLop NVARCHAR(50)
);

CREATE TABLE HOCVIEN (
    MaHV      INT PRIMARY KEY,
    TenHV     NVARCHAR(50),
    DienThoai VARCHAR(50),
    MaLop     VARCHAR(50),
    FOREIGN KEY (MaLop) REFERENCES LOP(MaLop)
);

CREATE TABLE MON (
    MaMon  VARCHAR(50) PRIMARY KEY,
    TenMon NVARCHAR(50),
    STC    INT
);

CREATE TABLE KETQUA (
    MaHV   INT,
    MaMon  VARCHAR(50),
    LanThi INT,
    Diem   FLOAT,
    PRIMARY KEY (MaHV, MaMon, LanThi),
    FOREIGN KEY (MaHV)  REFERENCES HOCVIEN(MaHV),
    FOREIGN KEY (MaMon) REFERENCES MON(MaMon)
);
GO